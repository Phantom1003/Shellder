#!/usr/bin/env python3
"""Fetch the Lucide icons the pages use and write them into ui/icons.js.

Lucide (https://lucide.dev, ISC licence) draws 24x24 strokes, the same
look as the system symbols the Swift app used. The left column is the name
the pages ask `icon()` for, the right one the Lucide icon. Run it again to
pick up a newer Lucide or a new name; the output is checked in.
"""
import json, re, sys, urllib.request

ICONS = {
    'lock': 'lock', 'unlock': 'lock-open', 'play': 'play', 'stop': 'square',
    'refresh': 'refresh-cw', 'xcircle': 'circle-x', 'hand': 'hand',
    'terminal': 'square-terminal', 'folder': 'folder', 'key': 'key-round',
    'eye': 'eye', 'eyeoff': 'eye-off', 'pencil': 'pencil', 'trash': 'trash',
    'plus': 'plus', 'gear': 'settings', 'doc': 'file-text', 'download': 'download',
    'log': 'scroll-text', 'close': 'x', 'check': 'check', 'circlecheck': 'circle-check',
    'warning': 'triangle-alert', 'question': 'circle-question-mark', 'shield': 'shield-half',
    'number': 'hash', 'server': 'server', 'laptop': 'laptop', 'chevron': 'chevron-right',
    'chevrondown': 'chevron-down', 'arrowup': 'arrow-up', 'arrowleft': 'arrow-left',
    'arrowright': 'arrow-right', 'folderplus': 'folder-plus', 'docplus': 'file-plus',
    'clock': 'clock', 'arrowupcircle': 'circle-arrow-up', 'arrowdowncircle': 'circle-arrow-down',
    'minuscircle': 'circle-minus', 'heart': 'heart-pulse', 'network': 'network',
    'copy': 'copy', 'link': 'square-arrow-out-up-right', 'home': 'house', 'info': 'info',
    'gauge': 'gauge', 'box': 'box', 'dashboard': 'layout-dashboard', 'globe': 'globe',
    'sun': 'sun', 'moon': 'moon', 'panel': 'panel-left', 'plug': 'plug', 'unplug': 'unplug',
    'eject': 'arrow-up-from-line', 'wrap': 'text-wrap', 'code': 'code-xml',
}
BASE = 'https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/'

out = {}
for name, lucide in ICONS.items():
    svg = urllib.request.urlopen(BASE + lucide + '.svg', timeout=30).read().decode()
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1).strip()
    inner = re.sub(r'\s+', ' ', inner).replace('> <', '><')
    out[name] = inner
    print(f'{name:16} <- {lucide}', file=sys.stderr)

with open('ui/icons.js', 'w') as f:
    f.write('// Generated by scripts/icons.py from Lucide (https://lucide.dev), ISC licence:\n')
    f.write('// the inner markup of each 24x24 icon, drawn in the text colour by icon().\n')
    f.write('export const ICONS = ' + json.dumps(out, indent=1, ensure_ascii=False) + ';\n')
